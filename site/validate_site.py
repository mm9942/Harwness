root=Path(__file__).parent/'dist'  # generated by build_content.py
class Page(HTMLParser):
 def __init__(self):
  super().__init__();self.ids=[];self.links=[];self.h1=0;self.lang=None;self.status=Counter()
 def handle_starttag(self,tag,attrs):
  a=dict(attrs)
  if 'id' in a:self.ids.append(a['id'])
  if tag=='h1':self.h1+=1
  if tag=='html':self.lang=a.get('lang')
  if 'data-status' in a:self.status[a['data-status']]+=1
  for k in ['href','src']:
   if k in a:self.links.append(a[k])

