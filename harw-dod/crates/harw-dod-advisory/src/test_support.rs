//! Test-Fehlertyp und Fixtures dieser Crate. Nur unter `#[cfg(test)]`.
//!
//! # Zweck
//! `define_test_error!` ersetzt `panic!`/`unwrap`/`expect` in Tests (Bible
//! R087/R165/R182). [`Fixture`] baut eine Miniatur-advisory-db und
//! `Cargo.lock`-Dateien in einem temporären Verzeichnis — nie committete
//! Testdaten, damit keine unsichtbaren Zeichen im Repository landen (die
//! Tests erzeugen sie zur Laufzeit aus `\u{…}`-Escapes).
//!
//! # Nebenläufigkeit
//! Jede Fixture hat ihr eigenes Verzeichnis; Tests laufen parallel.
//!
//! # Fehler
//! Alle Helfer liefern [`TestResult`].
//!
//! # Examples
//! ```rust,ignore
//! let fixture = Fixture::new()?;
//! let lock = fixture.write_lockfile("Cargo.lock", &[("tokio", "1.8.0", Some(CRATES_IO))])?;
//! ```

use std::fs;
use std::path::PathBuf;

harw_test_support::define_test_error!(pub(crate));

/// Der `source`-Wert eines crates.io-Pakets im `Cargo.lock`.
pub(crate) const CRATES_IO: &str = "registry+https://github.com/rust-lang/crates.io-index";

/// Ein temporäres Verzeichnis mit kanonischem Wurzelpfad.
///
/// `ReadScope` vergleicht kanonische Pfade; ein Symlink im Temp-Pfad
/// (etwa `/tmp` → `/private/tmp`) ließe sonst jeden Zugriff scheitern.
pub(crate) struct Fixture {
    // Hält das Verzeichnis bis zum Ende des Tests am Leben.
    _dir: tempfile::TempDir,
    /// Kanonische Wurzel der Fixture.
    pub(crate) root: PathBuf,
}

impl Fixture {
    /// Legt ein neues, leeres Fixture-Verzeichnis an.
    pub(crate) fn new() -> TestResult<Self> {
        let dir = tempfile::tempdir().map_err(ctx("Temp-Verzeichnis anlegen"))?;
        let root = dir
            .path()
            .canonicalize()
            .map_err(ctx("Temp-Verzeichnis kanonisieren"))?;
        Ok(Self { _dir: dir, root })
    }

    /// Wurzel der Miniatur-advisory-db (wird erst bei der ersten Advisory
    /// angelegt).
    pub(crate) fn db(&self) -> PathBuf {
        self.root.join("advisory-db")
    }

    /// Schreibt `crates/<krate>/<file_name>` in die Datenbank.
    pub(crate) fn write_advisory(
        &self,
        krate: &str,
        file_name: &str,
        content: &str,
    ) -> TestResult<PathBuf> {
        let dir = self.db().join("crates").join(krate);
        fs::create_dir_all(&dir).map_err(ctx("Crate-Verzeichnis anlegen"))?;
        let path = dir.join(file_name);
        fs::write(&path, content).map_err(ctx("Advisory schreiben"))?;
        Ok(path)
    }

    /// Schreibt ein `Cargo.lock` mit den Einträgen `(name, version, source)`.
    pub(crate) fn write_lockfile(
        &self,
        file_name: &str,
        packages: &[(&str, &str, Option<&str>)],
    ) -> TestResult<PathBuf> {
        let path = self.root.join(file_name);
        fs::write(&path, lockfile_text(packages)).map_err(ctx("Lockfile schreiben"))?;
        Ok(path)
    }
}

/// Der Text eines `Cargo.lock` (Format v4) mit den angegebenen Einträgen.
pub(crate) fn lockfile_text(packages: &[(&str, &str, Option<&str>)]) -> String {
    let mut content =
        String::from("# This file is automatically generated by Cargo.\nversion = 4\n");
    for (name, version, source) in packages {
        content.push_str(&format!(
            "\n[[package]]\nname = \"{name}\"\nversion = \"{version}\"\n"
        ));
        if let Some(source) = source {
            content.push_str(&format!("source = \"{source}\"\n"));
        }
    }
    content
}

/// Eine Markdown-Advisory im Format der advisory-db.
///
/// - `versions`: der Inhalt des `[versions]`-Abschnitts.
/// - `extra`: zusätzliche Zeilen im `[advisory]`-Abschnitt (darf leer sein).
pub(crate) fn advisory_md(
    id: &str,
    package: &str,
    versions: &str,
    extra: &str,
    title: &str,
) -> String {
    format!(
        "```toml\n[advisory]\nid = \"{id}\"\npackage = \"{package}\"\ndate = \"2099-01-01\"\n{extra}\n\n[versions]\n{versions}\n```\n\n# {title}\n\nBeschreibung.\n"
    )
}
